def detail_edges(parent):
 result=[]
 for id,leaves in BOUNDARY[parent].items():
  _,a,b,name,_=BY_ID[id]
  for leaf in leaves:result.append((f'{parent}.{leaf}' if a==parent else a,f'{parent}.{leaf}' if b==parent else b,id,name))
 return result+LOCAL[parent]

def validate_dfd():
 assert len(BY_ID)==len(FLOWS)
 allowed=set(ACTORS)|set(STORES)|set(TITLES)
 assert all(a in allowed and b in allowed for _,a,b,_,_ in FLOWS)
 for parent in TITLES:
  expected={id for id,a,b,_,_ in FLOWS if parent in (a,b)}
  assert set(BOUNDARY[parent])==expected,(parent,expected^set(BOUNDARY[parent]))
  for a,b,id,name in detail_edges(parent):
   if id.startswith('L'):assert a.startswith(parent+'.') and b.startswith(parent+'.')
   else:
    original=BY_ID[id]
    assert (parent if a.startswith(parent+'.') else a)==original[1]
    assert (parent if b.startswith(parent+'.') else b)==original[2]
  assert {x for a,b,_,_ in detail_edges(parent) for x in (a,b) if x.startswith(parent+'.')}=={f'{parent}.{i}' for i in [1,2,3]}
 return {'canonical_flows':len(FLOWS),'external_flows':sum(x[0].startswith('F') for x in FLOWS),'interfunctional_flows':sum(x[0].startswith('I') for x in FLOWS),'all_5_boundaries_balanced':True,'leaf_titles_from_single_source':True}
