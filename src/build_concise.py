def table(w,title,headers,rows,widths=None):
 number=f'{w.app_letter}.{w.app_tables.get(w.app_letter,0)+1}' if w.app_letter else str(w.tables+1)
 w.p('Сводные сведения приведены в таблице '+number+'.',keep=True)
 return w.table(title,headers,rows,widths,size=12)

